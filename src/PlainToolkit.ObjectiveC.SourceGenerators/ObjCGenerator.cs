using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace PlainToolkit.ObjectiveC.SourceGenerators
{
    [Generator]
    public sealed class ObjCGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var methods = ScanMethods(context);
            var signatures = methods.Select(static (method, _) => GetSignature(method))
                .Collect()
                .Select(static (items, _) =>
                    items.Distinct(SendMessageSignatureComparer.Instance).ToImmutableArray());

            context.RegisterSourceOutput(
                signatures,
                static (spc, signatures) =>
                {
                    var objcObjectSource = GenerateObjCObjectCode(signatures);

                    spc.AddSource("ObjCObject.g.cs", SourceText.From(objcObjectSource, Encoding.UTF8));
                });
        }

        private static IncrementalValuesProvider<IMethodSymbol> ScanMethods(IncrementalGeneratorInitializationContext context)
        {
            return context.SyntaxProvider
                .CreateSyntaxProvider(
                    static (node, _) => node is InvocationExpressionSyntax,
                    static (ctx, cts) =>
                    {
                        var invocation = (InvocationExpressionSyntax)ctx.Node;
                        var symbolInfo = ctx.SemanticModel.GetSymbolInfo(invocation, cts);

                        if (symbolInfo.Symbol is not IMethodSymbol methodSymbol)
                            return null;
                        if (methodSymbol.Name != "SendMessage")
                            return null;
                        if (!methodSymbol.IsGenericMethod)
                            return null;
                        if (methodSymbol.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) !=
                            "global::PlainToolkit.ObjectiveC.Runtime.ObjCObject")
                            return null;

                        return methodSymbol;
                    })
                .Where(static node => node is not null)
                .Select(static (node, _) => node!);
        }

        private static SendMessageSignature GetSignature(IMethodSymbol method)
        {
            var typeArguments = method.TypeArguments;

            return new SendMessageSignature(
                [.. typeArguments.Take(typeArguments.Length - 1)],
                typeArguments[typeArguments.Length - 1]);
        }

        private static string GenerateObjCObjectCode(ImmutableArray<SendMessageSignature> signatures)
        {
            var builder = new StringBuilder();

            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("namespace PlainToolkit.ObjectiveC.Generated;");
            builder.AppendLine();
            builder.AppendLine("public static class ObjCObjectInterceptors");
            builder.AppendLine("{");

            var objcSelName = "global::PlainToolkit.ObjectiveC.Runtime.ObjCSel";

            // 生成无参和只有一个参数
            builder.AppendLine($"    public unsafe TResult SendMessage<TResult>({objcSelName} msg)");
            GenerateBody(builder);
            builder.AppendLine("");

            builder.AppendLine($"    public unsafe void SendMessage<T>({objcSelName} msg, T arg)");
            GenerateBody(builder);
            builder.AppendLine("");

            builder.AppendLine($"    public unsafe TResult SendMessage<T, TResult>({objcSelName} msg, T arg)");
            GenerateBody(builder);
            builder.AppendLine("");

            // 生成剩下的
            for (var i = 1; i < 16; i++)
            {
                var range = Enumerable.Range(1, i + 1).Select(x => x.ToString()).ToArray();
                var generic = $"<T{string.Join(", T", range)}";
                var parameters = $"{string.Join(", ", range.Select(x => $"T{x} arg{x}"))}";

                builder.AppendLine($"    public unsafe void SendMessage{generic}>({objcSelName} msg, {parameters})");
                GenerateBody(builder);
                builder.AppendLine("");

                builder.AppendLine($"    public unsafe TResult SendMessage{generic}, TResult>({objcSelName} msg, {parameters})");
                GenerateBody(builder);
                if (i != 15)
                {
                    builder.AppendLine("");
                }
            }

            // foreach (var signature in signatures)
            // {
            //     var returnType = GetTypeName(signature.ReturnType);
            //     var parameters = string.Join(", ",
            //         signature.ParameterTypes.Select((type, index) => $"{GetTypeName(type)} arg{index}"));
            //
            //     builder.AppendLine($"    public {returnType} SendMessage({parameters})");
            //     builder.AppendLine("    {");
            //     builder.AppendLine("        throw new NotImplementedException();");
            //     builder.AppendLine("    }");
            //     builder.AppendLine();
            // }

            builder.AppendLine("}");

            return builder.ToString();

            void GenerateBody(StringBuilder sb)
            {
                builder.AppendLine("    {");
                builder.AppendLine("        throw new NotImplementedException();");
                builder.AppendLine("    }");
            }
        }

        private sealed record SendMessageSignature(ImmutableArray<ITypeSymbol> ParameterTypes, ITypeSymbol? ReturnType);

        private static string GetTypeName(ITypeSymbol symbol)
        {
            return symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        }

        private sealed class SendMessageSignatureComparer : IEqualityComparer<SendMessageSignature>
        {
            public static readonly SendMessageSignatureComparer Instance = new();

            public bool Equals(SendMessageSignature? x, SendMessageSignature? y)
            {
                if (ReferenceEquals(x, y))
                    return true;

                if (x is null || y is null)
                    return false;

                if (!SymbolEqualityComparer.Default.Equals(x.ReturnType, y.ReturnType))
                    return false;

                if (x.ParameterTypes.Length != y.ParameterTypes.Length)
                    return false;

                for (var i = 0; i < x.ParameterTypes.Length; i++)
                {
                    if (!SymbolEqualityComparer.Default.Equals(
                            x.ParameterTypes[i], y.ParameterTypes[i]))
                        return false;
                }

                return true;
            }

            public int GetHashCode(SendMessageSignature obj)
            {
                unchecked
                {
                    var hash = SymbolEqualityComparer.Default.GetHashCode(obj.ReturnType);

                    foreach (var type in obj.ParameterTypes)
                    {
                        hash = (hash * 31) + SymbolEqualityComparer.Default.GetHashCode(type);
                    }

                    return hash;
                }
            }
        }
    }
}
