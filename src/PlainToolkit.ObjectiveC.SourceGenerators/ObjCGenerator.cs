using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace PlainToolkit.ObjectiveC.SourceGenerators
{
    [Generator]
    public sealed class ObjCGenerator : IIncrementalGenerator
    {
        private const string ObjcObjectTypeName = "global::PlainToolkit.ObjectiveC.Runtime.ObjCObject";
        private const string ObjcSelTypeName = "global::PlainToolkit.ObjectiveC.Runtime.ObjCSel";
        private const string ObjcStringTypeName = "global::PlainToolkit.ObjectiveC.Runtime.ObjCString";
        private const string NIntTypeName = "nint";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var methods = ScanMethods(context);
            var infos = methods.Select(static (method, _) => GetSignature(method))
                .Collect();

            context.RegisterSourceOutput(
                infos,
                static (spc, infos) =>
                {
                    var infoDict = infos
                        .GroupBy(static info => (
                            info.Signature!.ParameterTypes.Length,
                            info.Method.ReturnsVoid))
                        .ToImmutableDictionary(
                            static group => group.Key,
                            static group => group.ToImmutableArray());

                    var objcObjectSource = GenerateObjCObjectCode(infoDict);

                    spc.AddSource("ObjCObjectInterceptors.g.cs", SourceText.From(objcObjectSource, Encoding.UTF8));
                });
        }

        private static IncrementalValuesProvider<MethodInfo> ScanMethods(
            IncrementalGeneratorInitializationContext context)
        {
            return context.SyntaxProvider
                .CreateSyntaxProvider(
                    static (node, _) => node is InvocationExpressionSyntax,
                    static (ctx, cts) =>
                    {
                        var invocation = (InvocationExpressionSyntax)ctx.Node;
                        var symbolInfo = ctx.SemanticModel.GetSymbolInfo(invocation, cts);

                        if (symbolInfo.Symbol is not IMethodSymbol methodSymbol)
                            return null;
                        if (methodSymbol.Name != "SendMessage")
                            return null;
                        if (!methodSymbol.IsGenericMethod)
                            return null;
                        if (methodSymbol.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) !=
                            "global::PlainToolkit.ObjectiveC.Runtime.ObjCObject")
                            return null;

                        var location = ctx.SemanticModel.GetInterceptableLocation(invocation, cts);

                        if (location is null)
                            return null;

                        return new MethodInfo(methodSymbol, location, null);
                    })
                .Where(static node => node is not null)
                .Select(static (node, _) => node!);
        }

        private static MethodInfo GetSignature(MethodInfo method)
        {
            return method with { Signature = GetSignatureCore(method.Method) };

            SendMessageSignature GetSignatureCore(IMethodSymbol m)
            {
                var typeArguments = m.TypeArguments;

                if (m.ReturnsVoid)
                {
                    return new SendMessageSignature(m.TypeArguments, null);
                }

                return new SendMessageSignature([.. typeArguments.Take(typeArguments.Length - 1)],
                    typeArguments[typeArguments.Length - 1]);
            }
        }

        private static string GenerateObjCObjectCode(
            ImmutableDictionary<(int Length, bool ReturnsVoid), ImmutableArray<MethodInfo>> methodInfos)
        {
            var builder = new StringBuilder();

            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine();
            builder.AppendLine("namespace System.Runtime.CompilerServices");
            builder.AppendLine("{");
            builder.AppendLine("    [AttributeUsage(AttributeTargets.Method, AllowMultiple = true)]");
            builder.AppendLine(
                "    file sealed class InterceptsLocationAttribute(int version, string data) : Attribute");
            builder.AppendLine("    {");
            builder.AppendLine("        public int Version { get; } = version;");
            builder.AppendLine("        public string Data { get; } = data;");
            builder.AppendLine("    }");
            builder.AppendLine("}");
            builder.AppendLine();
            builder.AppendLine("namespace PlainToolkit.ObjectiveC.Generated");
            builder.AppendLine("{");
            builder.AppendLine("    public static class ObjCObjectInterceptors");
            builder.AppendLine("    {");

            var first = true;
            foreach (var info in methodInfos)
            {
                var length = info.Key.Length;
                var returnsVoid = info.Key.ReturnsVoid;

                if (length == 0 && returnsVoid)
                    continue;

                if (!first)
                    builder.AppendLine();

                GenerateDeclaration(builder, length, returnsVoid, info.Value);
                GenerateBody(builder, info.Value);

                first = false;
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");

            return builder.ToString();

            void GenerateDeclaration(StringBuilder sb, int length, bool returnsVoid, ImmutableArray<MethodInfo> infos)
            {
                foreach (var location in infos.Select(static x => x.Location))
                {
                    sb.AppendLine($"        {location.GetInterceptsLocationAttributeSyntax()}");
                }

                var returnType = returnsVoid ? "void" : "TResult";

                var generic = GetGeneric(length, returnsVoid);
                var parameter = GetParameter(length);

                sb.AppendLine(
                    $"        public static unsafe {returnType} SendMessage{generic}(this in {ObjcObjectTypeName} obj, {ObjcSelTypeName} msg{(parameter.Length > 0 ? ", " : string.Empty)}{parameter})");
            }

            void GenerateBody(StringBuilder sb, ImmutableArray<MethodInfo> infos)
            {
                sb.AppendLine("        {");

                GenerateIf(sb, infos);

                sb.AppendLine();
                sb.AppendLine(
                    """            throw new global::System.Diagnostics.UnreachableException("Unexpected execution path.");""");

                sb.AppendLine("        }");
            }

            void GenerateIf(StringBuilder sb, ImmutableArray<MethodInfo> infos)
            {
                var signatures = new HashSet<SendMessageSignature>(SendMessageSignatureComparer.Instance);
                
                foreach (var info in infos)
                {
                    if (!signatures.Add(info.Signature!))
                        continue;
                    
                    var parameterTypes = info.Signature!.ParameterTypes;
                    var typeChecks = parameterTypes.Length == 1
                        ? [$"typeof(T) == typeof({parameterTypes[0]})"]
                        : parameterTypes.Select((x, i) => $"typeof(T{i + 1}) == typeof({GetTypeName(x)})");

                    if (info.Method.ReturnsVoid)
                    {
                        sb.AppendLine($"            if ({string.Join(" && ", typeChecks)})");
                    }
                    else
                    {
                        var and = parameterTypes.Length == 0 ? string.Empty : " && ";
                        sb.AppendLine(
                            $"            if ({string.Join(" && ", typeChecks)}{and}typeof(TResult) == typeof({GetTypeName(info.Signature!.ReturnType!)}))");
                    }

                    sb.AppendLine("            {");
                    GenerateFunctionPointer(sb, info);
                    sb.AppendLine("            }");
                }
            }

            void GenerateFunctionPointer(StringBuilder sb, MethodInfo info)
            {
                var result = info.Signature!.ReturnType is null
                    ? string.Empty
                    : $"var result = {ConvertReturnValue(info.Signature!.ReturnType!)}";
                var generic = string.Join(", ", info.Method.TypeArguments.Select(ConvertFunctionPointerSignature));
                var argument = string.Join(", ",
                    info.Signature.ParameterTypes.Select((x, i) =>
                        ConvertArgument(x, i, info.Signature.ParameterTypes.Length)));

                sb.AppendLine(
                    $"                {result}((delegate* unmanaged[Cdecl]<nint, nint, {generic}{(info.Method.ReturnsVoid ? ", void" : string.Empty)}>)global::PlainToolkit.ObjectiveC.Native.Message.MsgSend)(obj, msg{(info.Signature!.ParameterTypes.Length > 0 ? ", " : string.Empty)}{argument});");
                if (!info.Method.ReturnsVoid)
                {
                    sb.AppendLine(
                        $"                return global::System.Runtime.CompilerServices.Unsafe.As<{GetTypeName(info.Signature!.ReturnType!)}, TResult>(ref result);");
                }
            }
        }

        private static string GetGeneric(int length, bool returnsVoid)
        {
            if (length == 0)
                return returnsVoid ? string.Empty : "<TResult>";
            if (length == 1)
                return returnsVoid ? "<T>" : "<T, TResult>";
            return returnsVoid
                ? $"<{string.Join(", ", Enumerable.Range(1, length).Select(x => $"T{x}"))}>"
                : $"<{string.Join(", ", Enumerable.Range(1, length).Select(x => $"T{x}"))}, TResult>";
        }

        private static string GetParameter(int length)
        {
            if (length == 0)
                return string.Empty;
            if (length == 1)
                return "T arg";
            return string.Join(", ", Enumerable.Range(1, length).Select(x => $"T{x} arg{x}"));
        }

        private static string ConvertArgument(ITypeSymbol type, int argIndex, int argCount)
        {
            var str = GetTypeName(type);
            var argStr = argCount == 1 ? "arg" : $"arg{argIndex + 1}";
            var convertedArgStr =
                $"global::System.Runtime.CompilerServices.Unsafe.As<{(argCount == 1 ? "T" : $"T{argIndex + 1}")}, {ConvertFunctionPointerSignature(type)}>(ref {argStr})";
            return str switch
            {
                _ => convertedArgStr
            };
        }

        private static string ConvertFunctionPointerSignature(ITypeSymbol type)
        {
            var str = GetTypeName(type);
            return str switch
            {
                ObjcObjectTypeName => NIntTypeName,
                ObjcSelTypeName => NIntTypeName,
                ObjcStringTypeName => NIntTypeName,
                _ => str
            };
        }

        private static string ConvertReturnValue(ITypeSymbol type)
        {
            var str = GetTypeName(type);
            return str switch
            {
                ObjcObjectTypeName => $"({ObjcObjectTypeName})",
                ObjcSelTypeName => $"({ObjcSelTypeName})",
                ObjcStringTypeName => $"({ObjcStringTypeName})",
                _ => string.Empty
            };
        }

        private static string GetTypeName(ITypeSymbol symbol)
        {
            return symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        }

        private sealed record SendMessageSignature(ImmutableArray<ITypeSymbol> ParameterTypes, ITypeSymbol? ReturnType);

        private sealed record MethodInfo(
            IMethodSymbol Method,
            InterceptableLocation Location,
            SendMessageSignature? Signature);
        
        private sealed class SendMessageSignatureComparer : IEqualityComparer<SendMessageSignature>
        {
            public static readonly SendMessageSignatureComparer Instance = new();

            public bool Equals(SendMessageSignature? x, SendMessageSignature? y)
            {
                if (ReferenceEquals(x, y))
                    return true;

                if (x is null || y is null)
                    return false;

                if (!SymbolEqualityComparer.Default.Equals(x.ReturnType, y.ReturnType))
                    return false;

                if (x.ParameterTypes.Length != y.ParameterTypes.Length)
                    return false;

                for (var i = 0; i < x.ParameterTypes.Length; i++)
                {
                    if (!SymbolEqualityComparer.Default.Equals(
                            x.ParameterTypes[i], y.ParameterTypes[i]))
                        return false;
                }

                return true;
            }

            public int GetHashCode(SendMessageSignature obj)
            {
                unchecked
                {
                    var hash = SymbolEqualityComparer.Default.GetHashCode(obj.ReturnType);

                    foreach (var type in obj.ParameterTypes)
                    {
                        hash = (hash * 31) + SymbolEqualityComparer.Default.GetHashCode(type);
                    }

                    return hash;
                }
            }
        }
    }
}